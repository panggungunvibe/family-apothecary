const {readFileSync}=require('node:fs');
const {runInNewContext}=require('node:vm');
const assert=require('node:assert/strict');
const art=readFileSync('site/medicine-art.js','utf8');
const ocr=readFileSync('site/ocr.js','utf8');
const app=readFileSync('site/app.js','utf8').split('let medicines;')[0];
const context={Date,console};
runInNewContext(app+'\n'+art+'\n'+ocr+'\nthis.resolve=medicineMark;this.records=seed();this.draw=medicineArt;this.parseOcr=parseMedicineText;',context);
const expected=['formula:板蓝根','formula:连花清瘟','formula:藿香正气','icon:pill','icon:pill','icon:pill','herb:jinyinhua','herb:chenpi','herb:juhua','icon:iodine','icon:bandage','icon:swab'];
const marks=context.records.map(m=>context.resolve(m));
marks.forEach((a,i)=>assert.equal(a.kind+':'+(a.key||a.text||a.label),expected[i]));
assert.equal(context.resolve({name:'未知药品',category:'中药',plant:6}).kind,'text','Old random plant indices ignored');
assert.equal(context.resolve({name:'某某片',category:'西药',ingredients:'薄荷'}).key,'pill');
assert.equal(context.resolve({name:'藿香',category:'中药',ingredients:''}).kind,'text','Do not conflate 藿香 with 薄荷');
assert.equal(context.resolve({name:'新录入药品',category:'中成药',ingredients:'广藿香'}).key,'guanghuoxiang');
assert.equal(context.resolve({name:'新录入药品',category:'中成药',ingredients:'薄荷'}).key,'mint');
assert.equal(context.resolve({name:'板蓝根颗粒',category:'中成药',visualMode:'text'}).text,'板蓝根');
assert.equal(context.resolve({name:'创可贴',category:'其他',visualMode:'text'}).kind,'text');
assert.equal(context.resolve({name:'陈皮',category:'中药'}).key,'chenpi');
assert.deepEqual([...context.resolve({name:'六味地黄丸',category:'中成药'}).keys],['shudihuang','shanyao','shanzhuyu','moutan','fuling','zexie']);
assert.deepEqual([...context.resolve({name:'小柴胡颗粒',category:'中成药'}).keys],['chaihu','huangqin','gancao']);
assert.equal(context.resolve({name:'弹性绷带',category:'其他'}).key,'gauze');
assert.equal(context.resolve({name:'医用酒精喷雾',category:'其他'}).key,'alcohol');
assert.equal(context.resolve({name:'一次性手套',category:'其他'}).key,'gloves');
assert.equal(context.resolve({name:'未收录工具',category:'其他'}).key,'medicalbox');
for(const m of context.records){const html=context.draw(m);assert.ok(!html.includes('undefined'));assert.ok(html.includes('aria-label='));}
assert.ok(context.draw({name:'<img src=x onerror=1>',category:'中药'}).includes('&lt;'));
const parsed=context.parseOcr(`板蓝根颗粒\n成份：板蓝根\n生产日期：2024年06月12日\n有效期至：2026年06月11日\n有效期：24个月\n用法用量：一日3次 每次1袋\n包装规格：20袋`,'中成药');
assert.equal(parsed.name,'板蓝根颗粒');
assert.equal(parsed.ingredients,'板蓝根');
assert.equal(parsed.production,'2024-06-12');
assert.equal(parsed.expiry,'2026-06-11');
assert.equal(parsed.shelfLife,'24个月');
assert.equal(parsed.frequency,'一日3次');
assert.equal(parsed.dosage,'每次1袋');
assert.equal(parsed.quantity,'20袋');
assert.equal(parsed.category,'中成药');
assert.ok(!parsed.uncertainFields.includes('药品名称'));
const tool=context.parseOcr('医用弹性绷带\n规格：1卷','中药');
assert.equal(tool.category,'其他');
assert.equal(tool.name,'医用弹性绷带');
console.log('PASS: art matching, medical fallbacks, local OCR parsing, date normalization, escaping');
